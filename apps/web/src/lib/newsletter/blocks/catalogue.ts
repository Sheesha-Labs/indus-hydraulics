/**
 * The newsletter's block library: every kind of block an editor can add, its
 * fields and its defaults. Code, like a page template: a block is a shape;
 * what fills it (words, images, colours) is the editor's, stored on the
 * campaign.
 *
 * Adding a block: define it here, draw it in render.ts, and give it a preset
 * in presets.ts. `catalogue.test.ts` renders every block and every preset.
 */

import { BRAND } from '@indus/domain'
import type { BlockDef, FieldDef, ScalarFieldDef } from './types'

// ── Field helpers ────────────────────────────────────────────────

const text = (key: string, label: string, extra: { help?: string; placeholder?: string; max?: number } = {}): ScalarFieldDef => ({
  kind: 'text',
  key,
  label,
  ...extra,
})
const textarea = (key: string, label: string, help?: string): ScalarFieldDef => ({
  kind: 'textarea',
  key,
  label,
  help: help ?? '**bold**, [link text](https://…) and line breaks work here.',
})
const url = (key: string, label: string): ScalarFieldDef => ({
  kind: 'url',
  key,
  label,
  placeholder: 'https://… or /page on the site',
  help: 'A full address, a page on the site (/c/hydraulic-hoses), mailto: or tel:.',
})
const color = (key: string, label: string, allowBlank = true): ScalarFieldDef => ({ kind: 'color', key, label, allowBlank })
const image = (key: string, label: string, help?: string): ScalarFieldDef => ({ kind: 'image', key, label, help })
const toggle = (key: string, label: string, help?: string): ScalarFieldDef => ({ kind: 'toggle', key, label, help })
const select = (key: string, label: string, options: readonly (readonly [string, string])[]): ScalarFieldDef => ({
  kind: 'select',
  key,
  label,
  options: options.map(([value, l]) => ({ value, label: l })),
})

