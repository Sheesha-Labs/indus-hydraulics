export type VocabularyFamily = keyof typeof VOCABULARY_WORDS
export type VocabularyWord<F extends VocabularyFamily> = (typeof VOCABULARY_WORDS)[F][number]

/** True when `word` is one of the family's words (exact, case-sensitive). */
export function isVocabularyWord(family: VocabularyFamily, word: string): boolean {
  return (VOCABULARY_WORDS[family] as readonly string[]).includes(word)
}
