// Build-time only: run by scripts/gen-tokens.ts and by guards/tokens.drift.test.ts. Never imported by a kit.
import { clampChroma, formatHex, parse, type Color } from 'culori'

export type TokenKind = 'color' | 'font' | 'radius' | 'shadow' | 'size' | 'z'

export interface ExtToken {
  value: string
  kind: TokenKind
  signoff: 'awaiting' | 'approved'
  source: string
  /** Utility key when it differs from the token name (template widths: --io-w-well → w-io-well). */
  utility?: string
}

export type CoreTokens = Record<string, string>
export type ExtTokens = Record<string, ExtToken>

export interface Token {
  /** Name without the leading `--`, e.g. `io-card`. */
  name: string
  value: string
  kind: TokenKind
  ext: boolean
  /** Theme key without the namespace, e.g. `io-card`, `io-paper` (radius), `io-well` (size). */
  key: string
}

const HEADER =
  'GENERATED by packages/ops-ui/scripts/gen-tokens.ts from tokens/tokens.json and tokens/tokens.ext.json. Do not edit.'

const CORE_SIZES = new Set([
  'io-sidebar',
  'io-sidebar-collapsed',
  'io-page-x',
  'io-header',
  'io-btn-lg',
  'io-btn',
  'io-btn-sm',
  'io-chip',
  'io-tag',
])

function coreKind(name: string): TokenKind {
  if (name === 'io-sans' || name === 'io-serif') return 'font'
  if (name.startsWith('io-r-')) return 'radius'
  if (/^io-e\d$/.test(name)) return 'shadow'
  if (CORE_SIZES.has(name)) return 'size'
  return 'color'
}

function keyFor(name: string, kind: TokenKind, utility?: string): string {
  if (utility) return utility
  if (kind === 'radius') return name.replace(/^io-r-/, 'io-')
  return name
}

/** Every token, core first in handoff order, then ext in file order. */
export function collectTokens(core: CoreTokens, ext: ExtTokens): Token[] {
  const out: Token[] = []
  for (const [name, value] of Object.entries(core)) {
    const kind = coreKind(name)
    out.push({ name, value, kind, ext: false, key: keyFor(name, kind) })
  }
  for (const [name, t] of Object.entries(ext)) {
    if (name in core) throw new Error(`ext token ${name} shadows a core token`)
    out.push({
      name,
      value: t.value,
      kind: t.kind,
      ext: true,
      key: keyFor(name, t.kind, t.utility),
    })
  }
  const keys = new Map<string, string>()
  for (const t of out) {
    const k = `${t.kind}:${t.key}`
    if (keys.has(k))
      throw new Error(`${t.name} and ${keys.get(k)} produce the same ${t.kind} key ${t.key}`)
    keys.set(k, t.name)
  }
  return out
}

