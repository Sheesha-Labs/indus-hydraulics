function rootValue(t: Token): string {
  // next/font variables first so the self-hosted files win (05 §1.2); the handoff stacks stay as fallbacks.
  if (t.name === 'io-sans') return `var(--font-geist), ${t.value.replace(/,/g, ', ')}`
  if (t.name === 'io-serif') return `var(--font-instrument-serif), ${t.value.replace(/,/g, ', ')}`
  return t.value
}

export function tokensCss(tokens: Token[]): string {
  const lines = [`/* ${HEADER} */`, ':root {']
  let section = ''
  for (const t of tokens) {
    const s = t.ext ? `ext · ${t.kind}` : t.kind
    if (s !== section) {
      lines.push(`  /* ${s} */`)
      section = s
    }
    lines.push(`  --${t.name}: ${rootValue(t)};`)
  }
  lines.push('}', '')
  return lines.join('\n')
}

export function themeCss(tokens: Token[]): string {
  const of = (k: TokenKind) => tokens.filter((t) => t.kind === k)
  const l = [
    `/* ${HEADER} */`,
    '@theme inline {',
    '  /* Wipe Tailwind defaults: an off-token class compiles to nothing and token-usage.test.ts fails on it. */',
    '  --color-*: initial;',
    '  --font-*: initial;',
    '  --radius-*: initial;',
    '  --shadow-*: initial;',
    '  /* --spacing-* is NOT wiped: the numeric scale stays for spacing the handoff does not pin. */',
    '  --color-white: #ffffff;',
    '',
    '  /* colours */',
    ...of('color').map((t) => `  --color-${t.key}: var(--${t.name});`),
    '',
    '  /* families: Geist everywhere; font-mono deliberately resolves to Geist too */',
    '  --font-sans: var(--io-sans);',
    '  --font-serif: var(--io-serif);',
    '  --font-mono: var(--io-sans);',
    '',
    '  /* radii */',
    ...of('radius').map((t) => `  --radius-${t.key}: var(--${t.name});`),
    '',
    '  /* elevation */',
    ...of('shadow').map((t) => `  --shadow-${t.key}: var(--${t.name});`),
    '',
    '  /* sizes as spacing keys: w-io-sidebar, h-io-btn, px-io-page-x */',
    ...of('size').map((t) => `  --spacing-${t.key}: var(--${t.name});`),
    '',
    '  /* type roles */',
  ]
  for (const r of TEXT_ROLES) {
    l.push(`  --text-${r.key}: ${r.size};`)
    if (r.lineHeight) l.push(`  --text-${r.key}--line-height: ${r.lineHeight};`)
    if (r.letterSpacing) l.push(`  --text-${r.key}--letter-spacing: ${r.letterSpacing};`)
    if (r.fontWeight) l.push(`  --text-${r.key}--font-weight: ${r.fontWeight};`)
  }
  l.push(
    '}',
    '',
    '/* z-order: Tailwind has no z-index theme namespace, so each layer is a utility */'
  )
  for (const t of of('z'))
    l.push(`@utility z-${t.key.replace(/^io-z-/, 'io-')} {`, `  z-index: var(--${t.name});`, '}')
  l.push('')
  return l.join('\n')
}

function hexOf(value: string, tokens: Token[]): string {
  const mix = /^color-mix\(in oklch, var\(--([\w-]+)\) (\d+)%, transparent\)$/.exec(value)
  if (mix) {
    const base = tokens.find((t) => t.name === mix[1])
    if (!base) throw new Error(`color-mix references unknown token ${mix[1]}`)
    return overWhite(parseOrThrow(base.value), Number(mix[2]) / 100)
  }
  const c = parseOrThrow(value)
  return overWhite(c, c.alpha ?? 1)
}

function parseOrThrow(value: string): Color {
  const c = parse(value)
  if (!c) throw new Error(`cannot parse colour ${value}`)
  return c
}

/** sRGB hex of a colour composited over white at the given alpha (PDF has no transparency in fills we use). */
function overWhite(c: Color, alpha: number): string {
  const opaque = { ...c }
  delete opaque.alpha
  const hex = formatHex(clampChroma(opaque, 'oklch'))
  if (!hex) throw new Error(`cannot convert ${JSON.stringify(c)} to sRGB`)
  if (alpha >= 1) return hex.toUpperCase()
  const ch = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16))
  const mixed = ch.map((v) => Math.round(v * alpha + 255 * (1 - alpha)))
  return `#${mixed.map((v) => v.toString(16).padStart(2, '0')).join('')}`.toUpperCase()
}

export function pdfTokensTs(tokens: Token[]): string {
  const colours = tokens
    .filter((t) => t.kind === 'color')
    .map((t) => `  '${t.key}': '${hexOf(t.value, tokens)}',`)
  const radii = tokens
    .filter((t) => t.kind === 'radius')
    .map((t) => `  '${t.key}': ${parseFloat(t.value)},`)
  return [
    `// ${HEADER}`,
    '// sRGB equivalents for @react-pdf (culori oklch → sRGB, clamped; color-mix and alpha composited over white).',
    'export const IO_PDF_COLORS = {',
    ...colours,
    '} as const',
    '',
    'export const IO_PDF_RADII = {',
    ...radii,
    '} as const',
    '',
  ].join('\n')
}

export function generatedTs(tokens: Token[]): string {
  const keys = (k: TokenKind) => tokens.filter((t) => t.kind === k).map((t) => t.key)
  const arr = (name: string, items: string[]) =>
    [`export const ${name} = [`, ...items.map((i) => `  '${i}',`), '] as const', ''].join('\n')
  return [
    `// ${HEADER}`,
    '// Theme keys for cn() (tailwind-merge) and for the guard tests.',
    arr('IO_COLORS', keys('color')),
    arr(
      'IO_TEXT_ROLES',
      TEXT_ROLES.map((r) => r.key)
    ),
    arr(
      'IO_SERIF_ROLES',
      TEXT_ROLES.filter((r) => r.serif).map((r) => r.key)
    ),
    arr('IO_RADII', keys('radius')),
    arr('IO_SHADOWS', keys('shadow')),
    arr('IO_SIZES', keys('size')),
    arr(
      'IO_Z',
      keys('z').map((k) => k.replace(/^io-z-/, 'io-'))
    ),
    arr(
      'IO_VARS',
      tokens.map((t) => `--${t.name}`)
    ),
    "/** Raw values, for the specimen's labels only. Style with classes, never with these. */",
    'export const IO_VALUES: Readonly<Record<string, string>> = {',
    ...tokens.map(
      (t) =>
        `  '--${t.name}': ${JSON.stringify(t.value).replace(/'/g, "\\'").replace(/^"|"$/g, "'")},`
    ),
    '}',
    '',
  ].join('\n')
}

/** Every generated file, keyed by its path relative to packages/ops-ui. */
export function generateAll(core: CoreTokens, ext: ExtTokens): Record<string, string> {
  const tokens = collectTokens(core, ext)
  return {
    'src/styles/tokens.css': tokensCss(tokens),
    'src/styles/theme.css': themeCss(tokens),
    'src/tokens.pdf.ts': pdfTokensTs(tokens),
    'src/tokens.generated.ts': generatedTs(tokens),
  }
}
